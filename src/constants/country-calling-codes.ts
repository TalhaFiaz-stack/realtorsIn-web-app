export const DEFAULT_COUNTRY_CALLING_CODE =
  COUNTRY_CALLING_CODES.find((c) => c.cca2 === "AE") ?? COUNTRY_CALLING_CODES[0];

export function findCountryByCca2(cca2: string): CountryCallingCode | undefined {
  return COUNTRY_CALLING_CODES.find(
    (c) => c.cca2.toUpperCase() === cca2.toUpperCase()
  );
}

export function findCountryByDial(dial: string): CountryCallingCode | undefined {
  const digits = dial.replace(/\D/g, "");
  return (
    COUNTRY_CALLING_CODES.find((c) => c.cca2 === "AE" && c.dial === digits) ||
    COUNTRY_CALLING_CODES.find((c) => c.dial === digits)
  );
}
